// Botao da Discovery incrementa o contador
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if (GPIO_Pin == GPIO_PIN_0)
    {
        uint32_t now = HAL_GetTick();

        // Debounce de 180 ms
        if ((now - lastButtonTick) >= 180)
        {
            lastButtonTick = now;

            if (counter < 255) {
                counter++;
            }
        }
    }
}


// Recepcao por interrupcao
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance != USART2) {
        return;
    }

    if (serverState == SERVER_WAIT_CMD &&
        rxByte == CMD_REQUEST)
    {
        counterSnapshot = counter;

        serverState = SERVER_SEND_COUNT;

        if (HAL_UART_Transmit_IT(
                &huart2,
                &counterSnapshot,
                1) != HAL_OK)
        {
            Error_Handler();
        }
    }
    else if (serverState == SERVER_WAIT_ACK &&
             rxByte == CMD_READY)
    {
        serverState = SERVER_SEND_TABLE;

        if (HAL_UART_Transmit_DMA(
                &huart2,
                tableBuffer,
                TABLE_SIZE) != HAL_OK)
        {
            Error_Handler();
        }
    }
    else
    {
        if (HAL_UART_Receive_IT(
                &huart2,
                &rxByte,
                1) != HAL_OK)
        {
            Error_Handler();
        }
    }
}


// Transmissao por interrupcao concluida
void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance != USART2) {
        return;
    }

    if (serverState == SERVER_SEND_COUNT)
    {
        serverState = SERVER_WAIT_ACK;

        // Agora aguarda a confirmacao do cliente
        if (HAL_UART_Receive_IT(
                &huart2,
                &rxByte,
                1) != HAL_OK)
        {
            Error_Handler();
        }
    }
    else if (serverState == SERVER_SEND_TABLE)
    {
        // DMA terminou de transmitir a tabela
        counter = 0;
        serverState = SERVER_WAIT_CMD;

        // Aguarda nova solicitacao
        if (HAL_UART_Receive_IT(
                &huart2,
                &rxByte,
                1) != HAL_OK)
        {
            Error_Handler();
        }
    }
}
